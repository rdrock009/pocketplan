// @vitest-environment jsdom
import '@testing-library/jest-dom/vitest'
import { afterEach, describe, expect, it } from 'vitest'
import { cleanup, render, screen, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import App from '../App'

afterEach(() => { cleanup(); localStorage.clear() })
type User = ReturnType<typeof userEvent.setup>
const metric = (id: string, value: string) => expect(screen.getByTestId(id)).toHaveTextContent(value)
async function start() { const user = userEvent.setup(); render(<App />); await user.click(screen.getByRole('button', { name: 'What If' })); return user }
async function fill(user: User, label: string, value: string) { const input = screen.getByLabelText(label); await user.clear(input); await user.type(input, value) }
async function transaction(user: User, amount = '500') { await fill(user, 'Scenario name', 'Headphones'); await fill(user, 'Scenario amount (₹)', amount); await user.click(screen.getByRole('button', { name: 'Preview decision' })) }
const apply = (user: User) => user.click(screen.getByRole('button', { name: 'Apply decision' }))
const undo = (user: User) => user.click(screen.getByRole('button', { name: 'Undo last decision' }))

describe('What If shared-state controls', () => {
  it('previews, discards, applies once, and undoes a purchase across both screens', async () => {
    const user = await start()
    await transaction(user)
    metric('whatif-current-cash', '₹9,950.00'); metric('whatif-proposed-cash', '₹9,450.00'); metric('whatif-delta-cash', '−₹500.00')
    metric('whatif-proposed-closing', '₹3,301.00'); metric('cash-balance', '₹9,950.00')
    await user.click(screen.getByRole('button', { name: 'Discard preview' }))
    metric('whatif-proposed-cash', '—'); metric('cash-balance', '₹9,950.00')
    await user.click(screen.getByRole('button', { name: 'Preview decision' }))
    await apply(user)
    expect(screen.getByRole('button', { name: 'Apply decision' })).toBeDisabled()
    await apply(user)
    metric('whatif-current-cash', '₹9,450.00')
    await user.click(screen.getByRole('button', { name: 'My Month' }))
    expect(screen.getAllByText('Headphones')).toHaveLength(1)
    expect(screen.getByText('7 Oct · One-off cost')).toBeInTheDocument()
    metric('cash-balance', '₹9,450.00'); metric('forecast-closing', '₹3,301.00')
    await user.click(screen.getByRole('button', { name: 'What If' })); await undo(user)
    metric('cash-balance', '₹9,950.00'); metric('forecast-closing', '₹3,801.00')
    expect(screen.getByRole('button', { name: 'Undo last decision' })).toBeDisabled()
  })
  it('previews a critical emergency without changing the committed health', async () => {
    const user = await start()
    await user.selectOptions(screen.getByLabelText('Scenario type'), 'emergency')
    await transaction(user, '12000')
    metric('whatif-proposed-cash', '−₹2,050.00')
    const proposedHealth = screen.getByRole('heading', { name: 'Proposed health' }).parentElement!
    expect(within(proposedHealth).getByText('Shortfall risk')).toBeInTheDocument()
    metric('cash-balance', '₹9,950.00')
    await user.click(screen.getByRole('button', { name: 'Discard preview' }))
    expect(screen.getByRole('button', { name: 'Apply decision' })).toBeDisabled()
  })
  it.each(['received', 'planned'])('applies and undoes %s extra income', async status => {
    const user = await start()
    await user.selectOptions(screen.getByLabelText('Scenario type'), 'income')
    await user.selectOptions(screen.getByLabelText('Scenario income status'), status)
    if (status === 'planned') await fill(user, 'Scenario date', '2026-10-20')
    await transaction(user, '1000')
    metric('whatif-proposed-cash', status === 'received' ? '₹10,950.00' : '₹9,950.00')
    metric('whatif-proposed-closing', '₹4,801.00')
    await apply(user)
    metric('expected-income', status === 'received' ? '₹2,000.00' : '₹3,000.00')
    await undo(user)
    metric('cash-balance', '₹9,950.00'); metric('expected-income', '₹2,000.00')
  })
  it('applies and undoes subscription cancellation', async () => {
    const user = await start()
    await user.selectOptions(screen.getByLabelText('Scenario type'), 'cancel-subscription')
    await user.click(screen.getByRole('button', { name: 'Preview decision' }))
    metric('whatif-proposed-bills', '₹3,500.00'); metric('whatif-proposed-closing', '₹4,000.00')
    await apply(user); metric('bill-reserve', '₹3,500.00')
    expect(screen.getByRole('button', { name: 'Preview decision' })).toBeDisabled()
    await undo(user); metric('bill-reserve', '₹3,699.00')
    expect(screen.getByRole('button', { name: 'Preview decision' })).toBeEnabled()
  })
  it('changes savings target and date while keeping cash and saved money untouched', async () => {
    const user = await start()
    await user.selectOptions(screen.getByLabelText('Scenario type'), 'savings-target')
    await fill(user, 'Proposed target (₹)', '2000')
    await user.click(screen.getByRole('button', { name: 'Preview decision' }))
    metric('whatif-proposed-savings', '₹1,500.00'); metric('whatif-proposed-free', '₹4,751.00')
    metric('whatif-proposed-cash', '₹9,950.00'); metric('whatif-proposed-saved', '₹500.00')
    await apply(user); metric('savings-reserve', '₹1,500.00'); await undo(user)
    await fill(user, 'Proposed target (₹)', '0')
    await user.click(screen.getByRole('button', { name: 'Preview decision' }))
    metric('whatif-proposed-savings', '₹0.00'); await apply(user); metric('saved-total', '₹500.00')
    await undo(user)
    await fill(user, 'Proposed target date', '2026-11-10')
    await user.click(screen.getByRole('button', { name: 'Preview decision' }))
    metric('whatif-proposed-savings', '₹0.00')
  })
  it('invalidates previews when fields change and after reset or My Month edits', async () => {
    const user = await start()
    await transaction(user)
    await fill(user, 'Scenario amount (₹)', '600')
    expect(screen.getByRole('button', { name: 'Apply decision' })).toBeDisabled()
    metric('whatif-proposed-cash', '—')
    await user.click(screen.getByRole('button', { name: 'Preview decision' })); await apply(user)
    await user.click(screen.getByRole('button', { name: 'My Month' }))
    await fill(user, 'Name', 'Manual purchase'); await fill(user, 'Amount (₹)', '100')
    await user.click(screen.getByRole('button', { name: 'Add expense' }))
    await user.click(screen.getByRole('button', { name: 'What If' }))
    expect(screen.getByRole('button', { name: 'Undo last decision' })).toBeDisabled()
    metric('whatif-current-cash', '₹9,250.00')
    await user.click(screen.getByRole('button', { name: 'Preview decision' }))
    await user.click(screen.getByRole('button', { name: 'Reset sample' }))
    expect(screen.getByRole('button', { name: 'Apply decision' })).toBeDisabled()
    metric('whatif-current-cash', '₹9,950.00')
  })
  it('offers useful empty states for a fresh month', async () => {
    const user = await start()
    await user.click(screen.getByRole('button', { name: 'Start fresh' }))
    await user.selectOptions(screen.getByLabelText('Scenario type'), 'cancel-subscription')
    expect(screen.getByText('Add an active subscription in My Month first.')).toBeInTheDocument()
    await user.selectOptions(screen.getByLabelText('Scenario type'), 'savings-target')
    expect(screen.getByText('Add a savings goal in My Month first.')).toBeInTheDocument()
    expect(screen.getByRole('button', { name: 'Preview decision' })).toBeDisabled()
  })
})
