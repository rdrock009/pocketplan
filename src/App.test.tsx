// @vitest-environment jsdom
import '@testing-library/jest-dom/vitest'
import { afterEach, describe, expect, it } from 'vitest'
import { cleanup, render, screen, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import App from './App'

afterEach(() => { cleanup(); localStorage.clear() })
type User = ReturnType<typeof userEvent.setup>

function metric(id: string, value: string) {
  expect(screen.getByTestId(id)).toHaveTextContent(value)
}

async function selectCategory(user: User, name: string) {
  await user.click(within(screen.getByRole('navigation', { name: 'Entry types' })).getByRole('button', { name: new RegExp(`^${name}`) }))
}

async function fill(user: User, label: string, value: string) {
  const input = screen.getByLabelText(label)
  await user.clear(input)
  await user.type(input, value)
}

async function enter(user: User, name: string, value: string, dateLabel = 'Transaction date', date = '2026-10-01') {
  await fill(user, 'Name', name)
  await fill(user, 'Amount (₹)', value)
  await fill(user, dateLabel, date)
}

describe('My Month complete shared-state flow', () => {
  it('shows explicitly labelled sample data and matching engine-derived values', () => {
    render(<App />)
    expect(screen.getByRole('heading', { name: 'My Month', level: 1 })).toBeInTheDocument()
    expect(screen.getByText('Sample data · fictional month')).toBeInTheDocument()
    metric('cash-balance', '₹9,950.00')
    metric('spendable-cash', '₹5,251.00')
    metric('daily-allowance', '₹228.30')
    metric('forecast-closing', '₹3,801.00')
    metric('saved-total', '₹500.00')
    metric('bill-reserve', '₹3,699.00')
    metric('savings-reserve', '₹1,000.00')
    metric('days-remaining', '23 days left')
  })

  it('runs a fresh month through income, spending, bills, renewals, savings, and reset', async () => {
    const user = userEvent.setup()
    render(<App />)
    await user.click(screen.getByRole('button', { name: 'Start fresh' }))
    expect(screen.getByText('Your fresh month')).toBeInTheDocument()
    metric('cash-balance', '₹10,000.00')
    metric('daily-allowance', '₹333.33')
    metric('days-remaining', '30 days left')
    expect(screen.queryByText('Lunch with friends')).not.toBeInTheDocument()

    await selectCategory(user, 'Income')
    await enter(user, 'Weekend work', '1000')
    await user.click(screen.getByRole('button', { name: 'Add income' }))
    metric('cash-balance', '₹11,000.00')
    metric('days-remaining', '29 days left')

    await selectCategory(user, 'Expenses')
    await enter(user, 'Lunch', '100')
    await user.click(screen.getByRole('button', { name: 'Add expense' }))
    metric('cash-balance', '₹10,900.00')
    metric('forecast-closing', '₹8,000.00')

    await selectCategory(user, 'Commitments')
    await enter(user, 'Rent', '2000', 'Due date', '2026-10-10')
    await user.click(screen.getByRole('button', { name: 'Add commitment' }))
    metric('bill-reserve', '₹2,000.00')
    metric('spendable-cash', '₹8,900.00')

    await selectCategory(user, 'Subscriptions')
    await enter(user, 'Weekly pass', '100', 'First renewal date', '2026-10-03')
    await user.selectOptions(screen.getByLabelText('Renewal frequency'), 'weekly')
    await user.click(screen.getByRole('button', { name: 'Add subscription' }))
    metric('bill-reserve', '₹2,400.00')
    expect(screen.getAllByRole('button', { name: /Pay remaining for Weekly pass due/ })).toHaveLength(4)

    await selectCategory(user, 'Savings')
    await fill(user, 'Name', 'Buffer')
    await fill(user, 'Target amount (₹)', '1000')
    await fill(user, 'Target date', '2026-10-30')
    await user.click(screen.getByRole('button', { name: 'Create savings goal' }))
    metric('savings-reserve', '₹1,000.00')
    metric('spendable-cash', '₹7,500.00')
    metric('daily-allowance', '₹258.62')

    await user.click(screen.getByRole('button', { name: 'Move money' }))
    await fill(user, 'Amount (₹)', '250')
    await user.click(screen.getByRole('button', { name: 'Record transfer' }))
    metric('cash-balance', '₹10,650.00')
    metric('saved-total', '₹250.00')
    metric('savings-reserve', '₹750.00')
    metric('spendable-cash', '₹7,500.00')

    await user.click(screen.getByRole('button', { name: 'Pay remaining for Rent due 10 Oct' }))
    metric('cash-balance', '₹8,650.00')
    metric('bill-reserve', '₹400.00')
    metric('spendable-cash', '₹7,500.00')
    expect(screen.queryByRole('button', { name: 'Pay remaining for Rent due 10 Oct' })).not.toBeInTheDocument()

    await selectCategory(user, 'Expenses')
    await enter(user, 'Partial pass', '40')
    const paymentSelect = screen.getByLabelText('Payment for')
    const option = within(paymentSelect).getByRole<HTMLOptionElement>('option', { name: /Weekly pass · 3 Oct/ })
    await user.selectOptions(paymentSelect, option.value)
    await user.click(screen.getByRole('button', { name: 'Add expense' }))
    metric('cash-balance', '₹8,610.00')
    metric('bill-reserve', '₹360.00')
    metric('spendable-cash', '₹7,500.00')
    await user.click(screen.getByRole('button', { name: 'Remove Partial pass' }))
    metric('cash-balance', '₹8,650.00')
    metric('bill-reserve', '₹400.00')

    await selectCategory(user, 'Savings')
    await user.click(screen.getByRole('button', { name: 'Move money' }))
    await user.selectOptions(screen.getByLabelText('Direction'), 'withdrawal')
    await fill(user, 'Amount (₹)', '50')
    await user.click(screen.getByRole('button', { name: 'Record transfer' }))
    metric('cash-balance', '₹8,700.00')
    metric('saved-total', '₹200.00')
    metric('savings-reserve', '₹800.00')
    metric('spendable-cash', '₹7,500.00')

    await selectCategory(user, 'Expenses')
    await user.click(screen.getByRole('button', { name: 'Remove Lunch' }))
    metric('cash-balance', '₹8,800.00')
    metric('forecast-closing', '₹7,600.00')

    await selectCategory(user, 'Income')
    await user.selectOptions(screen.getByLabelText('Income status'), 'planned')
    await enter(user, 'Future work', '500', 'Expected date', '2026-10-20')
    await user.click(screen.getByRole('button', { name: 'Add income' }))
    metric('cash-balance', '₹8,800.00')
    metric('expected-income', '₹500.00')
    metric('forecast-closing', '₹8,100.00')
    await user.click(screen.getByRole('button', { name: 'Receive now: Future work' }))
    metric('cash-balance', '₹9,300.00')
    metric('expected-income', '₹0.00')
    metric('forecast-closing', '₹8,100.00')

    await selectCategory(user, 'Subscriptions')
    await user.click(screen.getByRole('button', { name: 'Stop renewals: Weekly pass' }))
    metric('bill-reserve', '₹0.00')
    metric('forecast-closing', '₹8,500.00')

    await user.click(screen.getByRole('button', { name: 'Reset sample' }))
    metric('cash-balance', '₹9,950.00')
    metric('forecast-closing', '₹3,801.00')
    expect(screen.getByText('Sample data · fictional month')).toBeInTheDocument()
    expect(screen.queryByText('Weekly pass')).not.toBeInTheDocument()
    expect(screen.queryByRole('alert')).not.toBeInTheDocument()
  }, 20_000)

  it('blocks invalid savings withdrawals without changing cash or snapshot', async () => {
    const user = userEvent.setup()
    render(<App />)
    await selectCategory(user, 'Savings')
    await user.click(screen.getByRole('button', { name: 'Move money' }))
    await user.selectOptions(screen.getByLabelText('Direction'), 'withdrawal')
    await fill(user, 'Amount (₹)', '501')
    await user.click(screen.getByRole('button', { name: 'Record transfer' }))
    expect(screen.getByRole('alert')).toHaveTextContent('withdrawals exceed saved funds')
    metric('cash-balance', '₹9,950.00')
    metric('saved-total', '₹500.00')
    metric('days-remaining', '23 days left')
    await fill(user, 'Amount (₹)', '100')
    await user.click(screen.getByRole('button', { name: 'Record transfer' }))
    metric('cash-balance', '₹10,050.00')
    metric('saved-total', '₹400.00')
    expect(screen.queryByRole('alert')).not.toBeInTheDocument()
  })

  it('changes health and forecasts immediately after a large expense, then recovers on removal', async () => {
    const user = userEvent.setup()
    render(<App />)
    await fill(user, 'Name', 'Emergency hospital bill')
    await fill(user, 'Amount (₹)', '12000')
    await user.click(screen.getByRole('button', { name: 'Add expense' }))
    metric('cash-balance', '−₹2,050.00')
    metric('health-state', 'Shortfall risk')
    metric('first-shortfall', '7 Oct')
    await user.click(screen.getByRole('button', { name: 'Remove Emergency hospital bill' }))
    metric('cash-balance', '₹9,950.00')
    metric('health-state', 'On track')
    metric('forecast-closing', '₹3,801.00')
  })

  it('handles snapshot boundaries and final-day forecast without hiding outstanding bills', async () => {
    const user = userEvent.setup()
    render(<App />)
    await fill(user, 'Snapshot day', '2026-10-01')
    await user.click(screen.getByRole('button', { name: 'Apply snapshot day' }))
    expect(screen.getByRole('alert')).toHaveTextContent('cannot precede recorded transactions')
    metric('days-remaining', '23 days left')
    await fill(user, 'Snapshot day', '2026-10-30')
    await user.click(screen.getByRole('button', { name: 'Apply snapshot day' }))
    metric('days-remaining', '0 days left')
    metric('daily-allowance', '₹0.00')
    metric('forecast-closing', '₹5,251.00')
    expect(screen.queryByRole('alert')).not.toBeInTheDocument()
    await user.click(screen.getByText('See forecast assumptions and daily balances'))
    expect(screen.getByText(/No days remain to forecast/)).toBeInTheDocument()
  })

  it('supports choosing a different start date and shows useful empty states', async () => {
    const user = userEvent.setup()
    render(<App />)
    await fill(user, 'New month start', '2026-11-02')
    await user.click(screen.getByRole('button', { name: 'Start fresh' }))
    expect(screen.getByLabelText('Snapshot day')).toHaveValue('2026-11-01')
    metric('days-remaining', '30 days left')
    expect(screen.getByText(/No expenses yet/)).toBeInTheDocument()
    await selectCategory(user, 'Savings')
    await user.click(screen.getByRole('button', { name: 'Move money' }))
    expect(screen.getByText(/Create a savings goal first/)).toBeInTheDocument()
  })

  it('rejects zero amounts and invalid subscription dates while preserving financial totals', async () => {
    const user = userEvent.setup()
    render(<App />)
    await fill(user, 'Name', 'Invalid amount')
    await fill(user, 'Amount (₹)', '0')
    await user.click(screen.getByRole('button', { name: 'Add expense' }))
    expect(screen.getByRole('alert')).toHaveTextContent('greater than ₹0')
    metric('cash-balance', '₹9,950.00')
    await selectCategory(user, 'Subscriptions')
    await enter(user, 'Invalid renewal', '50', 'First renewal date', '2026-10-20')
    await fill(user, 'Last renewal date (optional)', '2026-10-10')
    await user.click(screen.getByRole('button', { name: 'Add subscription' }))
    expect(screen.getByRole('alert')).toHaveTextContent('end precedes')
    metric('bill-reserve', '₹3,699.00')
  })

  it('protects linked records and makes every remaining category removable', async () => {
    const user = userEvent.setup()
    render(<App />)
    await user.click(screen.getByRole('button', { name: 'Pay remaining for Room rent due 10 Oct' }))
    await selectCategory(user, 'Commitments')
    await user.click(screen.getByRole('button', { name: 'Remove Room rent' }))
    expect(screen.getByRole('alert')).toHaveTextContent('Remove linked payments')
    await selectCategory(user, 'Expenses')
    await user.click(screen.getByRole('button', { name: 'Remove Room rent' }))
    await selectCategory(user, 'Commitments')
    await user.click(screen.getByRole('button', { name: 'Remove Room rent' }))
    metric('bill-reserve', '₹199.00')
    await selectCategory(user, 'Income')
    await user.click(screen.getByRole('button', { name: 'Remove Tutoring' }))
    metric('cash-balance', '₹8,450.00')
    await selectCategory(user, 'Subscriptions')
    await user.click(screen.getByRole('button', { name: 'Remove Music membership' }))
    metric('bill-reserve', '₹0.00')
    await selectCategory(user, 'Savings')
    await user.click(screen.getByRole('button', { name: 'Remove Emergency buffer' }))
    expect(screen.getByRole('alert')).toHaveTextContent('Remove this goal’s transfers')
    await user.click(screen.getByRole('button', { name: 'Remove deposit 6 Oct' }))
    await user.click(screen.getByRole('button', { name: 'Remove Emergency buffer' }))
    metric('saved-total', '₹0.00')
    metric('savings-reserve', '₹0.00')
    metric('cash-balance', '₹8,950.00')
  })
})
